  let current = "en";
  let onApply = null;

  function lang() {
    return current;
  }

  function t(key, vars) {
    let text = STRINGS[current]?.[key] || STRINGS.en[key] || key;
    if (vars && typeof vars === "object") {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
      }
    }
    return text;
  }

  function setOnApply(fn) {
    onApply = fn;
  }

  function applyDom(langCode) {
    if (langCode === "he" || langCode === "en") current = langCode;
    else current = "en";

    const he = current === "he";
    document.documentElement.lang = current;
    document.documentElement.dir = he ? "rtl" : "ltr";
    document.body.classList.toggle("ui-he", he);

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (!key) return;
      const attr = el.getAttribute("data-i18n-attr");
      const text = t(key);
      if (attr) {
        el.setAttribute(attr, text);
        if (attr === "title") el.setAttribute("aria-label", text);
      } else el.textContent = text;
    });

    if (typeof onApply === "function") onApply(current);
  }

  return { t, lang, applyDom, setOnApply, STRINGS };
