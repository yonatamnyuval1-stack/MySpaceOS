function mergeExistingLocale(lang, obj) {
  const localePath = path.join(__dirname, "..", "apps", "shared", "i18n", "locales", `${lang}.js`);
  if (!fs.existsSync(localePath)) return 0;
  delete require.cache[require.resolve(localePath)];
  require(localePath);
  const existing = globalThis.MySpaceI18nMessages?.[lang];
  if (!existing || typeof existing !== "object") return 0;
  let merged = 0;
  for (const [key, value] of Object.entries(existing)) {
    if (!(key in obj)) {
      obj[key] = value;
      merged++;
    }
  }
  return merged;
}

